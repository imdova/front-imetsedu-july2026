import type { ReactNode } from "react";
import { NextIntlClientProvider } from "next-intl";
import { getMessages } from "next-intl/server";

import { FULL_CATALOGUE, type NamespaceScope } from "./scopes";

/**
 * A message provider that ships only what its subtree reads.
 *
 * Nested providers replace their parent's messages rather than merging, so each
 * route area states its own scope (see `./scopes`). Locale, formats and time
 * zone are resolved by next-intl exactly as for the root provider; only
 * `messages` is narrowed.
 *
 * `namespaces` picks whole namespaces. `keys`, when given, narrows a namespace
 * further to the listed keys — the public site passes the list generated by
 * `scripts/gen-public-message-keys.mjs`, because even the one namespace it needs
 * (`Marketing`) is mostly copy that server components render and never send.
 *
 * `getMessages()` is the same per-request catalogue the root used to pass whole,
 * so a key that is shipped is delivered unchanged — there is no second copy of
 * any string to drift out of date.
 */
export async function IntlScope({
  namespaces,
  keys,
  children,
}: {
  namespaces: NamespaceScope;
  /** Per-namespace key allow-list. A namespace without an entry ships whole. */
  keys?: Readonly<Record<string, readonly string[]>>;
  children: ReactNode;
}) {
  if (namespaces === FULL_CATALOGUE) {
    return <NextIntlClientProvider>{children}</NextIntlClientProvider>;
  }

  const all = (await getMessages()) as Record<string, Record<string, unknown> | undefined>;
  const picked: Record<string, unknown> = {};
  for (const ns of namespaces) {
    const messages = all[ns];
    if (!messages) continue;
    const allow = keys?.[ns];
    picked[ns] = allow
      ? Object.fromEntries(allow.filter((k) => k in messages).map((k) => [k, messages[k]]))
      : messages;
  }
  return <NextIntlClientProvider messages={picked}>{children}</NextIntlClientProvider>;
}
